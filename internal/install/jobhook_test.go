// copyBinary gives the rig its own copy of the program, so a test can move or delete it.
func copyBinary(t *testing.T, r *testrig.Rig) string {
	t.Helper()
	data, err := os.ReadFile(testrig.Binary(t))
	if err != nil {
		t.Fatal(err)
	}
	p := filepath.Join(t.TempDir(), "bladerunner")
	if err := os.WriteFile(p, data, 0o755); err != nil {
		t.Fatal(err)
	}
	r.Env.BinaryPath = p
	return p
}

func TestADeletedProgramIsDetectedAndRepairedByMovingIt(t *testing.T) {
	r := testrig.New(t, testrig.BaseConfig)
	bin := copyBinary(t, r)
	if _, _, err := r.Apply(); err != nil {
		t.Fatal(err)
	}
	if problem, err := r.Env.HookProblem(); err != nil || problem != "" {
		t.Fatalf("a fresh install has a problem: %q %v", problem, err)
	}

	if err := os.Remove(bin); err != nil {
		t.Fatal(err)
	}
	problem, err := r.Env.HookProblem()
	if err != nil || !strings.Contains(problem, "no longer exists") || !strings.Contains(problem, "every job would be refused") {
		t.Fatalf("problem = %q, %v: a deleted program must be reported", problem, err)
	}
	// Re-running apply from the program's new location rewrites the script to point at it.
	newBin := copyBinary(t, r)
	changed, _, err := r.Apply()
	if err != nil || !reflect.DeepEqual(changed, []string{"job-hook", "service-running"}) {
		t.Fatalf("changed=%v err=%v", changed, err)
	}
	script, _ := os.ReadFile(filepath.Join(r.Env.Layout.HooksDir(), "job-started.sh"))
	if !strings.Contains(string(script), newBin) || strings.Contains(string(script), bin) {
		t.Errorf("the script should call the program's new path:\n%s", script)
	}
	if code, _ := runHook(t, r, job("acme", "push")); code != 0 {
		t.Error("after the repair the owner's job must run")
	}
}
